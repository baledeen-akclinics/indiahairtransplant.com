            <section id="candidacy" data-toc>
              <h2>Is a Hair Transplant the Right Step for You?</h2>
              <p>
                Before asking which clinic to choose, the more important question is whether now is the right time for surgery. A <a href="<?= base_url('hair-transplant') ?>">hair transplant</a> produces the most consistent long-term outcomes when:
              </p>
              <ul style="margin: 10px 0 16px 20px; color: var(--bs-muted); line-height: 1.85; font-size: 14.5px;">
                <li>Hair loss has stabilised or is being managed with prescribed treatment such as Minoxidil or Finasteride</li>
                <li>The donor area has enough healthy hair to cover the planned area while preserving donor hair for future needs</li>
                <li>The expected result matches what is realistically possible at the patient's current stage of hair loss</li>
                <li>The patient is in good general health, with no active scalp condition or unmanaged medical concern</li>
              </ul>
              <p>
                If surgery is done while hair loss is still progressing, existing native hair may continue to thin around the transplanted area in the coming years. This can affect the overall result and may necessitate further treatment later.
              </p>
              <div class="bs-note">
                A responsible surgeon will discuss hair loss progression, medication, PRP, GFC, timing, and donor planning during the first consultation. If a clinic moves directly toward scheduling surgery without discussing these factors, patients should take time to reconsider before proceeding.
              </div>
            </section>

