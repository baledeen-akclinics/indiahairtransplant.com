              <h3>Delhi-specific aftercare considerations</h3>

              <div class="bs-info-grid">
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#127787;&#65039;</span>
                    <strong>Air Quality (November to January)</strong>
                  </div>
                  <p>Delhi's winter smog season can see PM2.5 levels exceed 200 micrograms per cubic metre during peak conditions. A healing scalp in the first two weeks post-surgery is particularly vulnerable. Keeping the scalp covered outdoors and limiting unnecessary exposure during this window is strongly advisable.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#128167;</span>
                    <strong>Water Quality</strong>
                  </div>
                  <p>Delhi's municipal water supply has a high total dissolved solids (TDS) content. The post-operative scalp wash protocol your clinic provides should specify water temperature, shampoo type, and wash technique. Using harsh products or high water pressure during early healing can affect graft stability and increase the risk of folliculitis.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#127774;</span>
                    <strong>Summer Heat (May to July)</strong>
                  </div>
                  <p>Ambient temperatures between 38 and 45&deg;C during Delhi summers significantly increase scalp perspiration during the early recovery window. Limiting outdoor exposure to early morning and evening hours and staying in air-conditioned environments during the first three weeks reduces healing complications.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#128664;</span>
                    <strong>Commuting and Headwear</strong>
                  </div>
                  <p>Delhi's traffic conditions often require extended commutes. Helmet use on two-wheelers must be avoided for 3 to 4 weeks post-surgery. If commuting is unavoidable in the early weeks, travelling by car or auto reduces the risk of graft trauma from headgear friction and scalp heat accumulation.</p>
                </div>
