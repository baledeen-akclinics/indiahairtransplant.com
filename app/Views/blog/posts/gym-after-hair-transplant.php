              <div class="bs-faq-list" id="faqList">

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">Can I do yoga after a hair transplant?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Light yoga involving seated or standing poses with no inversions is generally safe from week 3 onwards. Avoid any pose that places your head below your heart &mdash; such as downward dog, headstands, or forward folds &mdash; until at least week 6. Increased blood flow to the scalp during inversions can disturb healing grafts and elevate swelling in the early recovery window.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">When can I lift heavy weights after a hair transplant?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Light bodyweight exercises can begin around week 2. Moderate weights at 50 to 60 percent of your usual load are typically safe from week 4 onwards. Heavy lifting &mdash; including maximal effort compound lifts like deadlifts, squats, and overhead press &mdash; should be avoided until week 6 to 8, when grafts are fully anchored and scalp healing is complete. Heavy lifting raises intra-abdominal pressure and blood pressure, both of which can stress the healing scalp.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">What happens if I sweat too early after a hair transplant?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Sweat itself does not dislodge grafts, but excessive sweating in the first two weeks creates conditions that raise infection risk at open wound sites. Salt in sweat can irritate the scalp, soften healing scabs prematurely, and increase the chance of folliculitis. The risk is compounded in Indian summers where ambient temperatures are high. If you do sweat mildly, gently dab &mdash; never wipe &mdash; with a clean tissue.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">Can I ride a bike or two-wheeler after a hair transplant?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Short trips as a pillion passenger are possible from week 2 provided no helmet is worn. Wearing a helmet presses directly against newly implanted grafts in the recipient area, creating friction and pressure that can dislodge grafts or cause sweat accumulation beneath the scalp. Most surgeons advise avoiding helmet use for a minimum of 3 to 4 weeks. If commuting is unavoidable, consider travelling by auto or car for the first month.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">Can I play cricket after a hair transplant?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Cricket involves significant physical exertion, prolonged sun exposure, and for fielders the risk of being hit on the head. It should be avoided for a minimum of 4 to 6 weeks. Batting and bowling in particular involve rotational forces and elevated heart rate. Outdoor play also exposes the unprotected scalp to direct sun. Resume only after clearance from your surgeon and only when all scabs have fully resolved.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">Does exercise affect shock loss after a hair transplant?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Exercising too early does not directly cause shock loss, but it can worsen the conditions that trigger it. Elevated blood pressure, sweating, and physical trauma to the scalp in the first two weeks can increase the severity of shedding and slow the recovery of native follicles surrounding the transplanted area. Waiting until grafts are anchored before resuming workouts gives both transplanted and native follicles the best environment to recover.</p>
                  </div>
                </article>

