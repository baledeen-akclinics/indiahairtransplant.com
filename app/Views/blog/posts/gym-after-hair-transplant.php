            <section id="red-flags" data-toc>
              <h2>When to Call Your Surgeon After Exercising</h2>
              <p>
                Most patients who follow the phased timeline recover without complications. However, if you exercised too early or notice any of the following after physical activity, contact your IHT surgeon promptly rather than waiting for your next scheduled appointment.
              </p>

              <ul class="bs-flag-list">
                <li>Increased bleeding or oozing from any graft sites after physical activity</li>
                <li>Noticeable swelling in the forehead or scalp that was not present before exercise</li>
                <li>Small pimples or pustules appearing in the recipient or donor area after sweating</li>
                <li>Grafts visibly dislodged or missing from their implanted positions</li>
                <li>Persistent pain or throbbing in the scalp that worsens after exertion</li>
                <li>Fever or generalised discomfort in the days following premature exercise</li>
              </ul>

              <p>
                Complications from early exercise are uncommon when patients follow the phased return protocol. Most issues that do arise are manageable when identified and treated early. Never wait and hope &mdash; contact your clinic the same day if you are concerned.
              </p>

