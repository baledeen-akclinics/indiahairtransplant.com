              <p>
                The critical FUT-specific restriction is upper back and neck exercises. The strip donor scar at the back of the scalp can stretch if exercises involving the neck and upper back muscles &mdash; such as deadlifts, overhead press, pull-ups, and neck rolls &mdash; are resumed too early. A stretched scar becomes more visible long-term. FUT patients should discuss this specifically with their surgeon before returning to these movements.
              </p>
            </section>

            <!-- ============================================================
                 SECTION 4 — SPECIFIC ACTIVITIES
            ============================================================ -->
            <section id="specific-activities" data-toc>
              <h2>Specific Activities: When Is Each One Safe?</h2>
              <p>
                Patients often have questions about a specific activity rather than a general timeline. Here is clear guidance on the activities most commonly asked about at IHT post-operative consultations.
              </p>

              <div class="bs-info-grid">
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#129354;</span>
                    <strong>Weight Lifting</strong>
                  </div>
                  <p>Light bodyweight from week 2. Moderate weights (50 to 60 percent load) from week 4. Heavy compound lifts &mdash; deadlifts, squats, bench press at full load &mdash; from week 6 to 8. Heavy lifting raises intra-abdominal and intracranial pressure, which can stress the healing scalp even when you are not touching it.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#127939;</span>
                    <strong>Running &amp; Jogging</strong>
                  </div>
                  <p>Slow treadmill walking from week 2 in an AC environment. Jogging outdoors from week 3, provided temperature is below 30&deg;C and it is not peak sun hours. Full running intensity from week 4. In Indian summers, restrict outdoor running to early morning (before 7 AM) for the first month regardless of technique.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#129506;</span>
                    <strong>Yoga</strong>
                  </div>
                  <p>Standing and seated poses with no inversion from week 3. Full practice including inversions (downward dog, headstands, shoulder stands, forward folds) from week 6 onwards. Inversions redirect blood flow toward the scalp, which can increase swelling and disrupt healing grafts if done too early.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#127955;</span>
                    <strong>Cricket &amp; Outdoor Sports</strong>
                  </div>
                  <p>Avoid for a minimum of 4 to 6 weeks. Cricket involves prolonged outdoor sun exposure, significant physical exertion, and for fielders the risk of sudden head impact. Batting and bowling generate rotational forces and elevated heart rate. Resume only after full surgical clearance and complete scab resolution.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#127946;</span>
                    <strong>Swimming</strong>
                  </div>
                  <p>Avoid for at least 3 months. Chlorinated pool water and salt water both irritate healing grafts. Prolonged scalp moisture exposure slows the healing process and increases infection risk. Open water swimming additionally carries the risk of physical contact with waves and currents. This is one of the last activities to receive clearance.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#128664;</span>
                    <strong>Two-Wheeler / Bike Commuting</strong>
                  </div>
                  <p>Helmet use must be avoided for 3 to 4 weeks minimum. A helmet presses directly on recipient grafts, creates friction, traps heat, and causes localised sweating beneath the scalp. If commuting is essential, consider travelling by auto or car for the first month. Some surgeons allow a loose cotton cap beneath a helmet after week 3 &mdash; confirm this with your own surgeon before attempting it.</p>
                </div>
              </div>
            </section>

            <!-- ============================================================
                 SECTION 5 — THE SWEATING PROBLEM
            ============================================================ -->
            <section id="sweating" data-toc>
              <h2>The Sweating Problem: Why Indian Patients Need Extra Caution</h2>

              <div class="bs-media-row bs-media-row--compact">
                <div>
                  <p>
                    Most international hair transplant recovery guides are written for patients in Europe or North America, where ambient temperatures during recovery are typically between 15 and 25&deg;C. In India, patients recovering in summer months may face temperatures of 38 to 45&deg;C with high humidity. This changes the calculation for exercise significantly.
                  </p>
                  <h3>What sweat actually does to healing grafts</h3>
                  <p>
                    Sweat does not directly dislodge grafts once they have initial clot anchoring. But excessive scalp sweating in the first two weeks does three things that compromise recovery: it softens healing scabs before they are ready to detach naturally, it introduces salt and bacteria to open wound sites, and it creates a warm, moist microenvironment that accelerates bacterial growth and raises the risk of folliculitis.
                  </p>
                </div>
                <img
                  src="<?= base_url('assets/images/blog/hair-transplant-aftercare-iht.webp') ?>"
                  alt="Post hair transplant scalp care at IHT India clinic"
                  class="bs-content-img" width="420" height="300" loading="lazy" />
              </div>

              <h3>Practical strategies for Indian patients</h3>
              <p>
                Patients who have had a <a href="/hair-transplant-in-delhi">hair transplant in Delhi</a> or <a href="/hair-transplant-in-ludhiana">hair transplant in Ludhiana</a> during April through July need to take the summer heat seriously as a recovery variable. Practical measures that reduce sweating risk include:
              </p>
              <ul style="margin: 10px 0 14px 20px; color: var(--bs-muted); line-height: 1.8; font-size: 14.5px;">
                <li>Limiting outdoor time to before 7 AM and after 7 PM for the first three weeks</li>
                <li>Keeping indoor environments air-conditioned at 22 to 24&deg;C during the recovery window</li>
                <li>Avoiding any form of exercise that produces scalp sweating until week 3</li>
                <li>If mild sweating occurs, gently dab &mdash; never wipe &mdash; with a clean, dry tissue</li>
                <li>Staying well-hydrated to support overall healing, even during exercise restriction</li>
                <li>Scheduling the transplant procedure for cooler months (October to February) if recovery during peak summer is a concern</li>
              </ul>
              <div class="bs-note">
                If your scalp becomes red, develops small pimples, or shows increased tenderness after physical activity or heat exposure, contact your IHT surgeon promptly. These can be early signs of folliculitis which respond well to early treatment.
              </div>
            </section>

            <!-- ============================================================
                 SECTION 6 — DOS AND DON'TS
            ============================================================ -->
            <section id="dos-donts" data-toc>
              <h2>Exercise Dos and Don&rsquo;ts After a Hair Transplant</h2>

              <div class="bs-dos-donts">
                <div class="bs-dos-box">
                  <div class="bs-dos-head">What To Do</div>
                  <ul class="bs-dos-list">
                    <li>Walk gently indoors from day 4 in a temperature-controlled environment</li>
                    <li>Return to gym activity in a phased way &mdash; walking first, then light resistance, then moderate cardio, then full load</li>
                    <li>Exercise in air-conditioned environments only for the first three weeks</li>
                    <li>Wear loose, breathable fabrics that do not make contact with the scalp or recipient area</li>
                    <li>Shower promptly after any exercise session once your surgeon clears you for regular washing</li>
                    <li>Carry a clean tissue and gently dab the scalp if you feel warmth or moisture building</li>
                    <li>Get explicit clearance from your surgeon before resuming each new activity tier</li>
                    <li>Monitor scalp response after every session &mdash; redness or tenderness means slow down</li>
                  </ul>
                </div>
                <div class="bs-donts-box">
                  <div class="bs-donts-head">What To Avoid</div>
                  <ul class="bs-donts-list">
                    <li>Do not go to the gym or do any exercise that causes scalp sweating in the first two weeks</li>
                    <li>Do not wear helmets, tight caps, headbands, or anything pressing against the scalp for 3 to 4 weeks</li>
                    <li>Avoid outdoor exercise in direct sun for at least four weeks &mdash; the unprotected scalp burns easily</li>
                    <li>Do not do yoga inversions, headstands, or any pose placing the head below the heart for six weeks</li>
                    <li>Avoid heavy compound lifts &mdash; deadlifts, squats, overhead press at full load &mdash; for 6 to 8 weeks</li>
                    <li>Do not swim in any pool, river, or sea for at least three months</li>
                    <li>Avoid contact sports, cricket, football, or martial arts for at least 4 to 6 weeks</li>
                    <li>Do not use steam rooms, saunas, or hot tubs for at least one month</li>
                  </ul>
                </div>
