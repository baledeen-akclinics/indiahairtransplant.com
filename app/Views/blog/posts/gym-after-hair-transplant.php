            <!-- ============================================================
                 SECTION 1 — WHY EXERCISE IS RESTRICTED
            ============================================================ -->
            <section id="why-restricted" data-toc>
              <h2>Why Exercise Is Restricted After a Hair Transplant</h2>
              <p>
                A <a href="<?= base_url('hair-transplant') ?>">hair transplant</a> is a surgical procedure. Follicular units are extracted from the donor area and individually placed into recipient sites created across the scalp. In the days that follow, those grafts are not yet anchored by new tissue &mdash; they are held in place by dried plasma and the natural clotting process. They are at their most vulnerable in the first 7 to 14 days.
              </p>
              <p>
                Three specific risks make early exercise a genuine threat to your result:
              </p>

              <div class="bs-info-grid">
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#128137;</span>
                    <strong>Blood Pressure Spikes</strong>
                  </div>
                  <p>Exercise raises systemic blood pressure. In the scalp, this increased vascular pressure can cause minor bleeding at graft sites and, in the early days, physically dislodge grafts that have not yet formed new tissue anchors.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#128167;</span>
                    <strong>Sweat at Open Wound Sites</strong>
                  </div>
                  <p>Sweat contains salt, urea, and lactic acid. Excessive sweating across the scalp in the first two weeks irritates open wound sites, softens healing scabs prematurely, and creates conditions where bacterial infection and folliculitis become significantly more likely.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#128170;</span>
                    <strong>Physical Trauma to Grafts</strong>
                  </div>
                  <p>Strenuous activity involving bending, straining, or contact with the scalp &mdash; through gym equipment, helmets, sports headgear, or impact &mdash; can directly dislodge grafts that are not yet secured. Even wiping sweat roughly from the forehead carries this risk in the first week.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#127774;</span>
                    <strong>India-Specific: Heat and Humidity</strong>
                  </div>
                  <p>Patients in Delhi, Ludhiana, and Bangalore face ambient temperatures of 32 to 45&deg;C during summer months. Outdoor activity in this heat produces sweating at a rate that would be unusual in cooler climates. Even a short walk in peak summer can generate the kind of scalp perspiration that carries risk in the first two weeks post-surgery.</p>
                </div>
              </div>

              <div class="bs-note">
                <strong>Medical disclaimer:</strong> This article is for informational purposes only. Timelines vary by individual healing rate, graft count, and surgical technique. Always follow the specific post-operative instructions provided by your own surgeon. Contact your clinic directly with any concerns about your personal recovery.
              </div>
            </section>

            <!-- ============================================================
                 SECTION 2 — WEEK-BY-WEEK TIMELINE
            ============================================================ -->
            <section id="timeline" data-toc>
              <h2>Week-by-Week Exercise Timeline After a Hair Transplant</h2>
              <p>
                There is no single clearance date for returning to exercise. Different activities carry different levels of risk, and the timeline reflects that. The breakdown below applies to patients who have had a <a href="/fue-hair-transplant">FUE hair transplant</a>. FUT patients should refer to the technique-specific guidance in the next section.
              </p>

              <div class="bs-timeline">

                <div class="bs-tl-item">
                  <div class="bs-tl-dot red">Day<br>1&ndash;3</div>
                  <div class="bs-tl-card danger">
                    <strong>Complete Rest &mdash; No Physical Activity</strong>
                    <p>The scalp is in its most vulnerable state. Grafts are held only by initial clotting. Even gentle exertion that elevates heart rate is inadvisable. Short, slow walks within the home or clinic are acceptable. No outdoor walking in heat, no climbing stairs briskly, no lifting anything heavier than 5 kg. Sleep with head elevated at 30 to 45 degrees to minimise swelling.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot amber">Day<br>4&ndash;7</div>
                  <div class="bs-tl-card">
                    <strong>Light Walking Only &mdash; Indoors or Early Morning</strong>
                    <p>Gentle flat-surface walking of 15 to 20 minutes is appropriate, provided it does not produce sweating. In Indian summers, restrict this to air-conditioned indoor environments or early morning before 7 AM. Do not walk in direct sunlight. Avoid any activity that involves bending the head forward, heavy bags, or effort that raises your heart rate noticeably.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot amber">Week<br>2</div>
                  <div class="bs-tl-card">
                    <strong>Slow Treadmill Walk &mdash; No Sweating Rule Still Applies</strong>
                    <p>Light bodyweight exercises &mdash; gentle squats, slow treadmill walking at flat incline &mdash; become possible for most patients by the end of week 2, provided scabs have healed and there is no scalp irritation. The no-sweating rule still applies. Stop immediately if you feel your scalp becoming warm or moist. Gym sessions must be in air-conditioned environments only at this stage.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot navy">Week<br>3</div>
                  <div class="bs-tl-card">
                    <strong>Moderate Cardio &mdash; Brisk Walking, Light Yoga</strong>
                    <p>Most patients can progress to brisk walking, slow jogging, light resistance machines, and standing yoga poses from week 3 onwards. Avoid yoga inversions (downward dog, headstands, forward folds) until week 6. Monitor scalp response after each session &mdash; if redness, itching, or swelling increases, reduce intensity and allow more healing time.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot green">Week<br>4</div>
                  <div class="bs-tl-card success">
                    <strong>Most Gym Activities Cleared &mdash; Moderate Load</strong>
                    <p>By the four-week mark, grafts are well anchored and most regular gym activities can resume. Moderate weights at 50 to 60 percent of your usual working load, jogging, cycling, and group fitness classes are appropriate for the majority of patients. Continue to avoid contact sports, heavy compound lifts, and anything involving headgear pressing on the scalp.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot green">Week<br>6&ndash;8</div>
                  <div class="bs-tl-card success">
                    <strong>Full Workout Routine &mdash; HIIT, Heavy Lifting Cleared</strong>
                    <p>Full training load, including HIIT, heavy compound lifts, and high-intensity cardio, is typically safe from week 6 to 8. The scalp is fully healed, grafts are anchored, and normal physiological stress from exercise no longer poses a risk to the transplant result. Return to your pre-surgery workout intensity progressively rather than all at once.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot green">Month<br>3+</div>
                  <div class="bs-tl-card success">
                    <strong>Contact Sports, Swimming, Team Sports &mdash; Fully Cleared</strong>
                    <p>Swimming in chlorinated pools, contact sports including cricket, football, kabaddi, and martial arts, and any activity involving helmets or headgear are safe from the three-month mark in most patients. By this point the scalp is fully healed and follicles are well into the active growth phase of their recovery cycle.</p>
                  </div>
                </div>

              </div><!-- /bs-timeline -->

              <div class="bs-note">
                These timelines are general guidance for the majority of patients. Your surgeon may adjust them based on your graft count, healing response, and the technique used. Always get individual clearance before returning to high-intensity activity. Learn more about the full <a href="/hair-transplant-safety-and-recovery">hair transplant safety and recovery</a> process at IHT.
              </div>
            </section>

