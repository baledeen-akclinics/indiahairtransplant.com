            <section id="types" data-toc>
              <h2>Normal Shedding vs Shock Loss: Understanding the Difference</h2>
              <p>Normal shedding and shock loss are often confused, but they are not exactly the same. Both can happen after a hair transplant and are usually temporary.</p>
            <p> Normal shedding usually refers to the expected shedding of transplanted hair shafts as part of the recovery process. Shock loss may also involve temporary shedding of existing native hairs around the treated area due to the stress of the procedure. Understanding the difference helps patients know what is normal during recovery and when they should contact their doctor for guidance.</p>
