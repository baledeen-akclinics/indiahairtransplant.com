            <section id="red-flags" data-toc>
              <h2>When Should You Be Concerned? Signs to Watch For</h2>
              <p>
                Shock loss is an expected part of hair transplant recovery. However, certain signs fall outside the normal range and require prompt contact with your surgeon. The ability to distinguish routine shedding from a genuine complication matters significantly for outcomes.
              </p>

              <ul class="bs-flag-list">
                <li>Persistent pain, throbbing, or worsening swelling beyond day 5 after surgery</li>
                <li>Pus, discharge, or an unpleasant odour from the recipient or donor area at any stage</li>
                <li>Fever above 38&deg;C in the days immediately following the procedure</li>
                <li>No visible new hair growth whatsoever by months 8 to 9</li>
                <li>Large bald patches in the recipient zone showing zero signs of regrowth by month 6</li>
                <li>Continued active shedding beyond the three-month mark with no early growth appearing</li>
              </ul>

              <p>
                Complications are uncommon when procedures are performed by qualified surgeons operating under proper clinical protocols. Recognising warning signs early and seeking review promptly always leads to better outcomes than waiting.
              </p>

