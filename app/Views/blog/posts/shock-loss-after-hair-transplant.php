              <div class="bs-faq-list" id="faqList">

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">Is shock loss after a hair transplant permanent?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">No. Shock loss is temporary in almost all cases. The follicles remain alive and anchored beneath the scalp. Once the resting phase ends &mdash; typically between 3 and 6 months post-surgery &mdash; new hair growth resumes from those follicles. Permanent shock loss affecting native hairs is uncommon and is generally linked to pre-existing severe follicle miniaturisation rather than the procedure itself.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">How long does shock loss last after a hair transplant?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Active shedding typically lasts between 2 and 8 weeks. The scalp may look sparse for 2 to 3 months post-surgery &mdash; the period often called the ugly duckling phase. Visible improvement generally begins between months 4 and 6, with most patients reaching 80 to 90 percent of their final result by month 9.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">Can Minoxidil or PRP reduce shock loss after a transplant?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Yes. Topical Minoxidil applied from 7 to 10 days post-surgery supports scalp circulation and can shorten the resting phase. PRP or GFC therapy sessions starting 4 to 6 weeks after surgery deliver growth factors that accelerate follicle recovery. Patients using both approaches typically see earlier visible growth than those relying on medication alone.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">Does shock loss affect transplanted grafts or only native hairs?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Both. Normal shedding primarily involves transplanted hair shafts falling while follicles remain intact. Shock loss can additionally affect native hairs in the surrounding area, particularly those already weakened or miniaturised. Both follicle groups typically recover within 3 to 6 months.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">Will I look worse than before my transplant during shock loss?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">Some patients find months 2 and 3 leave them looking similar to or marginally thinner than their pre-surgery state. This is one of the most important things to prepare for before any hair transplant. By months 5 and 6 visible progress becomes clear, and the full result is typically evident by months 9 to 12.</p>
                  </div>
                </article>

                <article class="bs-faq-item" itemscope itemtype="https://schema.org/Question">
                  <button class="bs-faq-q" type="button" aria-expanded="false">
                    <span itemprop="name">Does FUE cause less shock loss than FUT?</span>
                    <i class="bs-faq-ico" aria-hidden="true"></i>
                  </button>
                  <div class="bs-faq-a" hidden itemprop="acceptedAnswer" itemscope itemtype="https://schema.org/Answer">
                    <p itemprop="text">FUE generally causes less donor area trauma because follicles are extracted individually rather than as a strip, which tends to reduce shock loss severity in that region. Shock loss in the recipient area occurs with both techniques because creating incisions and placing grafts generates localised trauma regardless of extraction method. Surgical skill and post-operative care have a greater bearing on outcomes than the technique used.</p>
                  </div>
