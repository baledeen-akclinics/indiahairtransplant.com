                 SECTION 4 — CAUSES
            ============================================================ -->
            <section id="causes" data-toc>
              <h2>Why Does Shock Loss Happen? The Biological Causes</h2>
              <p>
                Several overlapping biological mechanisms drive the shock loss response. Together, they explain why this shedding is predictable and expected rather than a sign that something has gone wrong surgically.
              </p>

              <div class="bs-info-grid">
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#129656;</span>
                    <strong>Temporary Blood Supply Disruption</strong>
                  </div>
                  <p>During both extraction and implantation, follicles are briefly detached from their established blood supply. This interruption is sufficient to push them into the resting phase. Growth resumes naturally once circulation is re-established through the healing scalp.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#9889;</span>
                    <strong>Localised Surgical Trauma</strong>
                  </div>
                  <p>Creating incision sites and placing grafts generates localised physical stress in the recipient area. Native hairs immediately surrounding this zone can respond to the trauma by entering telogen effluvium, even though those follicles were not directly operated on.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#128200;</span>
                    <strong>Tumescent Anaesthesia Effect</strong>
                  </div>
                  <p>The anaesthetic fluid injected into the scalp before surgery temporarily alters local blood flow and the follicle environment. In some patients this contributes to earlier shedding, particularly in the donor region where fluid pressure is concentrated.</p>
                </div>
                <div class="bs-info-card">
                  <div class="bs-info-card-head">
                    <span class="bs-info-card-ico">&#129516;</span>
                    <strong>Pre-existing Follicle Miniaturisation</strong>
                  </div>
                  <p>Hairs already weakened by <a href="<?= base_url('androgenetic-alopecia') ?>">androgenetic alopecia</a> have considerably less resilience and are far more susceptible to stress-induced shedding. Patients with more advanced hair loss at the time of surgery often experience a more pronounced shock loss response in their native hairs.</p>
                </div>
              </div>

              <p>
                Surgical technique directly influences shock loss severity. Precise instrument selection, controlled extraction depth, minimal out-of-body graft time, and careful incision design all reduce trauma to native follicles. These are standard practice at IHT, not optional extras.
              </p>
            </section>

            <!-- ============================================================
                 SECTION 5 — AFTERCARE
            ============================================================ -->
            <section id="aftercare" data-toc>
              <h2>What Aftercare Actually Helps Reduce Shock Loss?</h2>

              <div class="bs-media-row bs-media-row--compact">
                <div>
                  <p>
                    Shock loss severity is directly shaped by what happens in the days immediately after surgery. While it cannot be fully prevented, the right aftercare practices can shorten its duration and reduce how pronounced the shedding appears on the scalp.
                  </p>
                  <h3>Why the first ten days are critical</h3>
                  <p>
                    In the first week, transplanted grafts are held in place by dried plasma, not yet anchored by new tissue growth. Friction, pressure, heat, or physical impact during this window can dislodge grafts and deepen the shock loss response in surrounding native follicles.
                  </p>
                </div>
                <img
                  src="<?= base_url('assets/images/blog/hair-transplant-aftercare.png') ?>"
                  alt="Post hair transplant scalp care guidance at IHT India"
                  class="bs-content-img" width="420" height="300" loading="lazy" />
              </div>

              <div class="bs-dos-donts">
                <div class="bs-dos-box">
                  <div class="bs-dos-head">What To Do</div>
                  <ul class="bs-dos-list">
                    <li>Follow the post-op scalp washing protocol from day 3 exactly as instructed by your surgeon</li>
                    <li>Take all prescribed medications &mdash; anti-inflammatories and antibiotics &mdash; for the complete prescribed course</li>
                    <li>Sleep with head elevated at 30 to 45 degrees for the first week to minimise swelling</li>
                    <li>Begin Minoxidil as directed, typically 7 to 10 days post-surgery when scalp healing allows</li>
                    <li>Maintain a protein-rich diet with adequate iron, zinc, and biotin to support follicle recovery</li>
                    <li>Attend all scheduled follow-up appointments to allow proper monitoring of healing</li>
                  </ul>
                </div>
                <div class="bs-donts-box">
                  <div class="bs-donts-head">What To Avoid</div>
                  <ul class="bs-donts-list">
                    <li>Do not scratch, rub, or pick at the recipient area even if it feels itchy during the healing phase</li>
                    <li>Avoid direct sun exposure on the scalp for a minimum of four weeks post-surgery</li>
                    <li>Do not smoke or consume alcohol for at least two weeks &mdash; both impair blood flow and slow healing</li>
                    <li>Avoid gym sessions, heavy lifting, or activities causing significant sweating for three to four weeks</li>
                    <li>Do not swim in a chlorinated pool or use a steam room or sauna for at least one month</li>
                    <li>Avoid helmets, tight caps, or anything pressing against grafts during the first two weeks</li>
                  </ul>
                </div>
              </div>

              <h3>PRP and GFC therapy post-transplant</h3>
              <p>
                <a href="/prp-hair-treatment">PRP (Platelet-Rich Plasma)</a> and <a href="<?= base_url('gfc-hair-treatment') ?>">GFC (Growth Factor Concentrate)</a> therapy sessions beginning 4 to 6 weeks after surgery deliver concentrated growth factors directly into the scalp. This accelerates recovery of both transplanted and native follicles and typically results in a shorter, less pronounced shock loss phase. Patients combining post-transplant growth factor therapy with consistent Minoxidil use consistently report earlier visible growth than those using medication alone.
              </p>
              <div class="bs-note">
                Whether PRP or GFC is appropriate depends on individual scalp response. Your surgeon will assess this at your first post-operative follow-up and recommend the right protocol for your recovery.
              </div>

