                 SECTION 1 — WHAT IS SHOCK LOSS
            ============================================================ -->
            <section id="intro" data-toc>
              <h2>What Is Shock Loss After a Hair Transplant?</h2>
              <p>Shock loss, medically known as post-operative telogen effluvium, refers to the temporary shedding of hair that commonly occurs in the weeks following a hair transplant. It may affect the transplanted hairs and, in some cases, the existing hairs around the treated area. This happens because the scalp and hair follicles undergo temporary stress during the procedure, causing some hairs to enter the resting phase of the hair growth cycle earlier than usual.</p>

             <p>The most important thing to understand is that the hair shaft sheds, not the follicle itself. The follicle remains alive beneath the scalp and, in most cases, begins producing new hair as the growth cycle resumes. For this reason, shock loss is considered a normal part of the recovery process and is not a sign that the transplant has failed.</p>
                
              <p>At IHT, patients are informed about shock loss before the procedure so they know what to expect during recovery. Understanding this phase helps reduce unnecessary anxiety and allows patients to focus on proper aftercare while waiting for new growth to begin. In most cases, visible improvement starts gradually over the next few months, while the final hair transplant result is usually assessed around 12 months. </p>

              <div class="bs-note">
                <strong>Medical disclaimer:</strong> This article is for informational purposes only. Always follow the post-operative instructions provided by your own surgeon and contact your clinic directly if you have specific concerns about your individual recovery.
              </div>
            </section>

            <!-- ============================================================
