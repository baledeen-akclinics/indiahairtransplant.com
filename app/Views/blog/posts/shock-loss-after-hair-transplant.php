            <section id="timeline" data-toc>
              <h2>Month-by-Month Recovery Timeline After a Hair Transplant</h2>
              <p>
               A clear understanding of what happens at each stage can reduce much of the anxiety around shock loss. The timeline below explains the usual recovery pattern after an FUE hair transplant at IHT. However, the exact pace may vary depending on hair type, number of grafts, healing response, and the consistency with which aftercare instructions are followed. 

              </p>

              <div class="bs-timeline">

                <div class="bs-tl-item">
                  <div class="bs-tl-dot amber">Week<br>1</div>
                  <div class="bs-tl-card">
                    <strong>Surgery Day to Day 7 &mdash; Initial Healing</strong>
                    <p>Redness, minor swelling, and scabbing around the grafts are normal. Transplanted follicles sit as tiny stubble dots on the scalp surface. This is the highest-risk window for graft dislodgement. Aftercare must be followed precisely: no direct water pressure on grafts, sleep with the head elevated, do not touch or scratch the recipient area.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot amber">Week<br>2&ndash;3</div>
                  <div class="bs-tl-card">
                    <strong>The Stubble Phase &mdash; Early Encouragement</strong>
                    <p>Scabs flake away naturally. Transplanted hairs appear as short, visible stubble. Patients often feel encouraged during this window. It is also when the shedding phase is about to begin &mdash; preparing mentally for what comes in weeks three to five is important.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot red">Week<br>3&ndash;5</div>
                  <div class="bs-tl-card danger">
                    <strong>Shock Loss Begins &mdash; Shedding Is Medically Expected at This Stage</strong>
                    <p>This is the phase when many patients become concerned and contact the clinic. Transplanted hairs may start shedding, and the existing hair around the treated area can also appear thinner for some time. The scalp may look sparse or slightly patchy, but this does not mean the follicles are lost. They are in a resting phase and will gradually begin producing new hair. Continue the prescribed aftercare as advised, and do not stop or change any medication without consulting your surgeon.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot grey">Mo<br>2&ndash;3</div>
                  <div class="bs-tl-card">
                    <strong>The Waiting Period &mdash; The &ldquo;Ugly Duckling&rdquo; Phase</strong>
                    <p>Active shedding has largely settled. The scalp may look similar to or marginally thinner than before surgery. Beneath the surface, follicles are healing and preparing for active growth. Fine baby hairs often start emerging by the end of month three for patients with faster regrowth cycles.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot navy">Mo<br>4&ndash;6</div>
                  <div class="bs-tl-card success">
                    <strong>Early Growth Begins: The Turning Point</strong>
                    <p>By this stage, the transplanted hairs have matured, resulting in improved hairline definition, density, and overall coverage. Most patients achieve around 80–90% of their hair transplant results by the ninth month, with the remaining growth and thickening continuing gradually.</p>
                    <p>The final hair transplant results are usually assessed at 12 months, although some patients may continue to see gradual thickening and improvement after this, especially if they have naturally fine or slow-growing hair.</p>
                  </div>
                </div>

                <div class="bs-tl-item">
                  <div class="bs-tl-dot green">Mo<br>8&ndash;12</div>
                  <div class="bs-tl-card success">
                    <strong>Full Results Visible &mdash; Density and Coverage Complete</strong>
                    <p>Transplanted hairs have matured to their full calibre. Hairline definition, density, and coverage reflect the final surgical outcome. Most patients see 80 to 90 percent of their complete result by month nine. Hair continues maturing through month twelve and occasionally a little beyond for those with naturally fine or slow-growing hair.</p>
                  </div>
                </div>

