          <span>Is hair transplant permanent?</span>
          <i class="faq-ico" aria-hidden="true"></i>
        </button>
        <div class="faq-a" hidden="">
          A hair transplant is considered a long-term solution for pattern hair loss. The transplanted follicles are taken from the safe donor area, which is typically resistant to DHT (dihydrotestosterone), the hormone linked to genetic hair loss. However, existing non-transplanted hair can continue to thin over time, which is why proper planning and long-term care matter.
        </div>
      </article>

      <article class="faq-item">
        <button class="faq-q" aria-expanded="false">
          <span>How many grafts are needed for a hair transplant?</span>
          <i class="faq-ico" aria-hidden="true"></i>
        </button>
        <div class="faq-a" hidden="">
          Grafts required depend on your baldness level, the area to be covered, hair thickness, donor strength, and your long-term plan. Small hairline correction may need around 1,000–1,500 grafts, while advanced hair loss can require 3,000–5,000+ grafts, sometimes across more than one sitting.
        </div>
      </article>

      <article class="faq-item">
        <button class="faq-q" aria-expanded="false">
          <span>Does a hair transplant look natural?</span>
          <i class="faq-ico" aria-hidden="true"></i>
        </button>
        <div class="faq-a" hidden="">
          Yes, when planned correctly. Natural results depend on hairline design, angle and direction of implantation, density planning, and surgeon involvement, not just graft numbers.
        </div>
      </article>

      <article class="faq-item">
        <button class="faq-q" aria-expanded="false">
          <span>What are the side effects of a hair transplant?</span>
          <i class="faq-ico" aria-hidden="true"></i>
        </button>
        <div class="faq-a" hidden="">
          Common side effects include mild swelling, redness, scabbing, numbness, or mild discomfort in the treated areas. Temporary shedding (shock loss) may happen in the first few weeks. Most effects settle within 5–7 days, and serious complications are uncommon when surgery is performed under proper medical standards.
        </div>
      </article>

      <article class="faq-item">
        <button class="faq-q" aria-expanded="false">
          <span>Can hair loss continue after a hair transplant?</span>
          <i class="faq-ico" aria-hidden="true"></i>
        </button>
        <div class="faq-a" hidden="">
          Yes. Hair loss can continue in untreated areas because it is progressive. That’s why good planning focuses on donor preservation, age-appropriate hairline design, and long-term coverage rather than short-term density.
        </div>
      </article>

