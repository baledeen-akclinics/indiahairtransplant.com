    <h2 class="results-title">What Exactly Is Dandruff?</h2>

    <div class="results-divider" aria-hidden="true">
      <span class="line"></span>
      <span class="cross">✚</span>
      <span class="line"></span>
    </div>

    <div class="cs-wrap">
      <div class="cs-content">

        <p class="cs-text">
        Dandruff is a scalp condition in which the outer layer of skin sheds more rapidly than usual, causing visible flakes in the hair. These flakes can be white or slightly yellow and are often linked with itching or mild scalp irritation.
        </p>

        <p class="cs-text">
        Under normal circumstances, the scalp continually renews itself by shedding dead skin cells and replacing them with new ones. When this process speeds up, dead cells accumulate and clump together, forming visible flakes.
        </p>

        <p class="cs-text">
        In many cases, dandruff is linked to a naturally occurring yeast called <strong>Malassezia</strong>, which resides on most people's scalps. In some individuals, this microorganism can cause scalp irritation and accelerate skin cell turnover.
        </p>

        <p class="cs-text">
        Although dandruff is very common, it can sometimes be mistaken for other scalp conditions such as <strong>seborrheic dermatitis</strong>, <strong>scalp psoriasis</strong>, or <strong>scalp folliculitis</strong>, which may require different treatments.
        </p>

      </div>
    </div>

