    <h2 class="results-title">Techniques Used for Body Hair Transplant</h2>

    <div class="results-divider" aria-hidden="true">
      <span class="line"></span>
      <span class="cross">✚</span>
      <span class="line"></span>
    </div>

    <div class="cs-wrap">
      <div class="cs-content">

        <p class="cs-text">
          Body Hair Transplant (BHT) is a technically demanding procedure that requires careful surgeon selection. Unlike scalp hair, body hair varies significantly in growth pattern, depth, and healing response.
          <br><br>
          For this reason, the surgery must be planned and performed by an experienced hair transplant surgeon who understands donor behaviour and graft handling.
        </p>

        <ul class="iht-acc-list">
          <li>
            <strong>FUE (Follicular Unit Extraction)</strong><br>
            FUE is the most common technique for extracting and transplanting body hair. It allows no-strip extraction from the beard and other body donor areas.
            <br><br>
            Individual follicular units are extracted one at a time using fine punches, enabling controlled harvesting while minimising trauma to the surrounding skin. This method allows selective extraction based on donor suitability and is commonly used when scalp donor hair alone is insufficient.
          </li>

          <li>
            <strong>Bio-FUE Technique (Signature Procedure)</strong><br>
            Bio-FUE is a signature, customised technique at IHT Clinic, developed for cases involving weak donor areas or extended procedure durations.
            <br><br>
            This approach builds on the standard FUE method and is supported by custom-designed tools such as CTS, which enhance control, precision, and procedural safety during follicle extraction and handling. Bio-FUE contributes to improved outcomes, with observed benefits reported in the range of approximately 20–30% in suitable cases.
          </li>
        </ul>

      </div>
    </div>

  </div>
</section>


