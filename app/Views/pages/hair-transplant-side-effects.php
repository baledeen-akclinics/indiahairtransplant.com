                  <div class="iht-acc-item">
                    <button class="iht-acc-q" aria-expanded="false">
                      <span class="iht-acc-title">Infection</span>
                      <span class="iht-acc-ico" aria-hidden="true"></span>
                    </button>
                    <div class="iht-acc-a" hidden>
                      Infection rates in sterile, medically supervised hair transplant environments are below 1%. The scalp's high vascularity — it has an exceptionally rich blood supply — makes it naturally resistant to infection compared to other body areas. Risk factors include diabetes, immune suppression, smoking, and procedures performed in non-sterile settings. Signs include persistent throbbing pain after day five, increased localised warmth, pus or discharge, and fever above 38°C. Treatment with oral antibiotics is typically effective. Untreated infections can lead to folliculitis (inflamed follicle pockets) or, very rarely, abscess formation.
                    </div>
                  </div>

                  <div class="iht-acc-item">
                    <button class="iht-acc-q" aria-expanded="false">
                      <span class="iht-acc-title">Folliculitis (Pimple-Like Bumps)</span>
                      <span class="iht-acc-ico" aria-hidden="true"></span>
                    </button>
                    <div class="iht-acc-a" hidden>
                      Folliculitis presents as small, acne-like pustules or inflamed bumps over the recipient area, typically appearing four to eight weeks after surgery as transplanted hairs begin to push through the scalp surface. It is caused by inflammation of the follicle during this re-emergence phase, not bacterial infection in most cases. Mild folliculitis resolves on its own. Persistent cases are managed with topical antibiotic ointment and, where needed, short-course oral antibiotics. Warm saline compresses help reduce inflammation. Patients with a history of scalp acne or seborrheic dermatitis may be more prone to this.
                    </div>
                  </div>

                </div>

                <div class="iht-acc-col">

                  <div class="iht-acc-item">
                    <button class="iht-acc-q" aria-expanded="false">
                      <span class="iht-acc-title">Visible Scarring at the Donor Site</span>
                      <span class="iht-acc-ico" aria-hidden="true"></span>
                    </button>
                    <div class="iht-acc-a" hidden>
                      FUE leaves tiny, dot-like marks (0.8–1.0mm) at each extraction site. When performed with appropriate density limits and proper technique, these marks are effectively invisible once hair reaches a normal length. Over-harvesting — extracting too many grafts from a limited area — is the primary cause of visible donor thinning or scarring. This is a planning and technique issue, not an inherent risk of the procedure itself. FUT (strip method) leaves a linear scar at the back of the scalp; its visibility depends on hair length and healing tendency. Patients with a known predisposition to keloid or hypertrophic scarring should discuss this explicitly during consultation.
                    </div>
                  </div>

                  <div class="iht-acc-item">
                    <button class="iht-acc-q" aria-expanded="false">
                      <span class="iht-acc-title">Unnatural Hairline or Poor Graft Survival</span>
                      <span class="iht-acc-ico" aria-hidden="true"></span>
                    </button>
                    <div class="iht-acc-a" hidden>
                      An unnatural-looking hairline is entirely avoidable — it results from poor surgical design, not an inherent limitation of the procedure. A natural hairline requires irregularity, correct angulation (hair angles forward and slightly downward), and single-hair grafts at the very front edge. Poor graft survival (below the expected 85–95% survival rate) is caused by graft desiccation during long procedures, excessive handling, incorrect implantation angle, poor recipient site creation, or inadequate post-operative care. These are technique and protocol issues. Choosing a clinic where a qualified, experienced surgeon — not a trained technician — performs the critical steps of extraction and implantation is the primary safeguard.
                    </div>
