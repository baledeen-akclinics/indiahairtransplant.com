  <section class="internal-white">
    <div class="container">

      <h2 class="results-title">Shock Loss After Hair Transplant: The Most Misunderstood Side Effect</h2>
      <div class="results-divider" aria-hidden="true">
        <span class="line"></span><span class="cross">✚</span><span class="line"></span>
      </div>

      <div class="cs-wrap">
        <div class="cs-content">

          <p class="cs-text">
            Of all hair transplant side effects, <strong>shock loss</strong> (medically termed <em>telogen effluvium</em>) causes the most distress — primarily because patients are not adequately counselled about it beforehand. Understanding it is critical to not panicking and discontinuing care at the worst possible moment.
          </p>

          <p class="cs-text">
            <strong>What it is:</strong> Shock loss is the temporary shedding of hair — both existing native hair around the transplant zone and the newly implanted grafts themselves — triggered by the physical stress of surgery. It typically begins two to six weeks after the procedure. The hair appears to be "falling out," and patients who were not warned about this sometimes believe the transplant has failed.
          </p>

          <p class="cs-text">
            <strong>Why it happens:</strong> Hair follicles respond to surgical stress by entering the telogen (resting) phase of the growth cycle earlier than usual. This is a survival mechanism — the follicle temporarily suspends active growth to conserve energy during the healing process.
          </p>

          <p class="cs-text">
            <strong>What actually happens underneath:</strong> The follicle itself is not damaged or destroyed. The root remains intact below the scalp surface. After the resting phase — which typically lasts two to four months — the follicle re-enters the anagen (active growth) phase and new hair begins to emerge.
          </p>

          <p class="cs-text">
            <strong>The timeline:</strong> Most patients see initial regrowth at three to four months, meaningful density improvement at six to eight months, and full results at twelve to eighteen months. Some patients — particularly those with a very dense, well-vascularised scalp — may retain most of their transplanted hair without significant shedding at all.
          </p>

          <ul class="iht-acc-list">
            <li><strong>Months 1–2:</strong> Shock loss may occur. Normal native and transplanted hair shed. This is expected — not a sign of failure.</li>
            <li><strong>Months 3–4:</strong> Follicles re-enter anagen. Fine, light-coloured "baby hairs" begin to emerge.</li>
            <li><strong>Months 5–6:</strong> Hair thickens and darkens progressively. Visible improvement is noticeable in most patients.</li>
            <li><strong>Months 8–10:</strong> Substantial density restoration. Hairline shape becomes clearly defined.</li>
            <li><strong>Months 12–18:</strong> Full, final result. Hair texture, thickness, and density reach maturity.</li>
          </ul>

