          </button>
          <div class="faq-a" hidden>
            Scalp and forehead swelling is most pronounced on days two to four after surgery — it can descend to the forehead and around the eyes, which looks alarming but is normal. It generally subsides completely within seven to ten days. Your surgeon will typically prescribe a short course of corticosteroids and advise sleeping with the head elevated for the first five nights to help manage and reduce swelling.
