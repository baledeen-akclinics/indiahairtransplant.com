          </button>
          <div class="faq-a" hidden>
            FUE (Follicular Unit Extraction) leaves tiny, dot-like marks of 0.8–1.0mm at each extraction site. When performed with correct density limits and spacing, these are effectively invisible once hair grows to a normal length. Over-harvesting — taking too many grafts from a limited area — is the preventable cause of visible donor scarring. At IHT, responsible donor area planning is a standard part of every surgical plan. Patients with a personal or family history of keloid scarring should discuss this risk specifically during their pre-operative consultation.
