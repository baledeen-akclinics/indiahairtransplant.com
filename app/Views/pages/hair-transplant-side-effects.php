          </button>
          <div class="faq-a" hidden>
            Shock loss (telogen effluvium) is the temporary shedding of existing or newly transplanted hair triggered by the physical stress of surgery. It typically begins two to six weeks post-procedure and is a completely normal part of the hair growth cycle response. Most patients regain full density between nine and twelve months as the resting follicles re-enter the active growth phase. Shock loss is not a sign of transplant failure — the follicle root remains intact below the scalp.
