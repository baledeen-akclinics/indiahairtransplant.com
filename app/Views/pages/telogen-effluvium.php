      <h2 class="results-title">Overview of Telogen Effluvium</h2>

      <div class="results-divider">
        <span class="line"></span><span class="cross">✚</span><span class="line"></span>
      </div>

      <div class="cs-content">

        <p class="cs-text">
          Telogen effluvium is a common hair loss condition characterised by <strong>sudden and excessive hair shedding across the scalp.</strong> It happens when more hair follicles prematurely enter the <strong>telogen (resting) phase</strong> of the hair growth cycle.
        </p>

        <p class="cs-text">
          Under normal conditions, only a small percentage of hair follicles are in the resting phase, while most continue active growth. However, certain physical or emotional stressors can disrupt this balance, causing more hairs to enter the shedding phase simultaneously.
        </p>

        <p class="cs-text">
          As a result, people may notice <strong>increased hair fall during washing, combing, or brushing,</strong> along with a gradual decrease in overall hair volume. In many cases, telogen effluvium is <strong>temporary,</strong> and hair growth may eventually return to normal once the hair cycle stabilises.
        </p>

        <p class="cs-text">
          Understanding how telogen effluvium affects the hair growth cycle helps dermatologists assess the condition and recommend appropriate management strategies based on the severity of hair shedding.
        </p>

      </div>

    </div>
