          <p class="cs-text">
            Androgenetic alopecia is the medical term for hereditary pattern hair loss. It is the most common type of hair loss observed in both men and women, and it usually develops gradually rather than suddenly.
          </p>

          <p class="cs-text">
            In men, it often begins with a receding hairline or thinning around the crown. In women, it more frequently manifests as diffuse thinning over the top of the scalp or a wider middle parting, while the frontal hairline is usually maintained.
          </p>

          <p class="cs-text">
            It is also commonly called <strong>male-pattern hair loss</strong> and <strong>female-pattern hair loss</strong>, depending on its appearance. Although the pattern may vary, the underlying issue is similar: genetically sensitive hair follicles respond to hormonal influences and gradually produce finer hair.
          </p>

        </div>
