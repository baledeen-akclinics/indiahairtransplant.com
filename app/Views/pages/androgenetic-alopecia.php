            Androgenetic alopecia is a progressive form of hair loss in which hair follicles gradually shrink. This process is primarily linked to genetic predisposition and the influence of DHT, a hormone that can cause certain hair follicles to shrink in susceptible individuals.
          </p>

          <p class="cs-text">
            As the follicles miniaturise, the hair growth cycle shortens, and the strands grow back thinner, weaker, and less visible. Over time, this results in reduced hair density, widening part lines, temple recession, or thinning at the crown, depending on the pattern of hair loss.
          </p>

          <p class="cs-text">
            Because this change occurs slowly, many people notice increased scalp visibility or decreased volume before recognising it as a medical hair loss issue. Early detection is important because timely treatment may help slow progression and improve hair retention.
          </p>

