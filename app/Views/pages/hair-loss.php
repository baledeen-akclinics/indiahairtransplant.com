    <div class="results-divider" aria-hidden="true">
      <span class="line"></span>
      <span class="cross">✚</span>
      <span class="line"></span>
    </div>

    <div class="cs-wrap">
      <div class="cs-content">

        <p class="cs-text">Hair loss is a medical condition where hair follicles gradually lose their ability to produce healthy hair fibres. It happens when the balance between hair growth and shedding is disturbed, resulting in a visible decrease in hair density over time.</p>
        <p class="cs-text">Each hair grows from a follicle beneath the scalp and follows a natural growth cycle. When follicles become weakened or sensitive, they start producing finer, shorter hair, a process called follicle miniaturisation. Over time, some follicles may stop producing visible hair entirely.</p>
        <p class="cs-text">It is also important to understand that not all hair fall indicates hair loss. Losing approximately 50–100 strands of hair daily is typically part of the normal hair growth cycle and is called hair shedding.</p>
        <p class="cs-text">However, when hair fall becomes persistent or is accompanied by visible thinning, widening of the hair part, or increased scalp visibility, it may indicate ongoing hair loss and requires proper medical assessment.</p>
