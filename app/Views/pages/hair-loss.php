<section class="internal-grey"> 
  <div class="container">

    <h2 class="results-title">Stages of Hair Loss</h2>
    <div class="results-divider" aria-hidden="true">
      <span class="line"></span><span class="cross">✚</span><span class="line"></span>
    </div>

    <div class="cs-wrap">
      <div class="cs-content">

        <p class="cs-text">
          Hair loss is closely linked to changes in the normal hair growth cycle. Every hair follicle follows a continuous cycle of growth, transition, and rest, which allows old hair to shed and new hair to grow.
        </p>

        <p class="cs-text">
          When this cycle functions normally, hair density is maintained. Hair loss develops when the cycle is repeatedly disturbed over time, affecting how hair grows and regenerates.
        </p>

        <div class="iht-acc" data-accordion="multi">
          <div class="iht-acc-shell">

            <div class="iht-acc-cols">

              <!-- LEFT COLUMN -->
              <div class="iht-acc-col">

                <!-- Anagen Phase -->
                <div class="iht-acc-item">
                  <button class="iht-acc-q" type="button" aria-expanded="false">
                    <span class="iht-acc-title">Anagen Phase (Growth Phase)</span>
                    <span class="iht-acc-ico"></span>
                  </button>
                  <div class="iht-acc-a" hidden>
                    <p><strong>Duration:</strong> Typically 2 to 8 years</p>

                    <p>
                      The anagen phase is the active growth stage during which hair follicles produce strong, thick hair strands. In a healthy scalp, nearly 85–90% of hair follicles remain in this phase.
                    </p>

                    <p>
                      When the anagen phase is shortened due to genetic sensitivity, hormonal imbalance, or nutritional deficiencies, hair may gradually become thinner and weaker with each growth cycle.
                    </p>
                  </div>
                </div>

                <!-- Catagen Phase -->
                <div class="iht-acc-item">
                  <button class="iht-acc-q" type="button" aria-expanded="false">
                    <span class="iht-acc-title">Catagen Phase (Transition Phase)</span>
                    <span class="iht-acc-ico"></span>
                  </button>
                  <div class="iht-acc-a" hidden>
                    <p><strong>Duration:</strong> Around 2–3 weeks</p>

                    <p>
                      The catagen phase is a short transitional stage where hair growth stops and the follicle begins to shrink and detach from its blood supply.
                    </p>

                    <p>
                      Only a small percentage of hair follicles remain in this phase at any given time, but it plays an important role in the natural hair growth cycle.
                    </p>
                  </div>
                </div>

              </div>

              <!-- RIGHT COLUMN -->
              <div class="iht-acc-col">

                <!-- Telogen Phase -->
                <div class="iht-acc-item">
                  <button class="iht-acc-q" type="button" aria-expanded="false">
                    <span class="iht-acc-title">Telogen Phase (Resting & Shedding Phase)</span>
                    <span class="iht-acc-ico"></span>
                  </button>
                  <div class="iht-acc-a" hidden>
                    <p><strong>Duration:</strong> Approximately 2–3 months</p>

                    <p>
                      During the telogen phase, hair follicles rest and hair growth temporarily stops. At the end of this phase, hair strands shed to make way for new growth.
                    </p>

                    <p>
                      Normally about 10–15% of scalp hair is in this phase. When too many follicles enter this stage prematurely, noticeable hair shedding may occur.
                    </p>
                  </div>
                </div>

              </div>

            </div>

          </div>
        </div>

