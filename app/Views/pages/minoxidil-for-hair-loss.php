        <p class="cs-text">
          Minoxidil is generally considered safe when used correctly; however, it may not be appropriate for everyone. A thorough medical evaluation is recommended before starting treatment to assess overall health, scalp condition, and potential risk factors.
        </p>

        <p class="cs-text">
          Minoxidil should be avoided or used only under strict medical supervision if you:
        </p>

        <ul class="feature-list">
          <li>Have uncontrolled cardiovascular conditions or a history of significant heart disease</li>
          <li>Experience low blood pressure or are taking antihypertensive medication (especially with oral minoxidil)</li>
          <li>Have active scalp infections, open wounds, severe dermatitis, or inflammatory scalp conditions</li>
          <li>Have a known allergy or hypersensitivity to minoxidil or its ingredients</li>
          <li>Are pregnant, planning pregnancy, or breastfeeding</li>
        </ul>

        <p class="cs-text">
          In such cases, alternative treatment options may be considered based on scalp examination and medical history. Self-medication without professional guidance can increase the risk of side effects or reduce treatment effectiveness.
