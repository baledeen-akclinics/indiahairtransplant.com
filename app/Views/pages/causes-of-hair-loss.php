    <h2 class="results-title">Genetic Hair Loss (Androgenetic Alopecia)</h2>

    <div class="results-divider" aria-hidden="true">
      <span class="line"></span>
      <span class="cross">✚</span>
      <span class="line"></span>
    </div>

    <div class="cs-wrap">

      <div class="cs-img">
        <img src="<?= base_url('assets/images/genetic-hair-loss.png') ?>" alt="Genetic hair loss and androgenetic alopecia affecting hair follicles">
      </div>

      <div class="cs-content">

        <p class="cs-text">
          Genetic hair loss is one of the most common reasons for hair thinning in both men and women. 
          It occurs when hair follicles become sensitive to a hormone called 
          <strong>dihydrotestosterone (DHT)</strong>. Over time, this sensitivity causes the follicles 
          to gradually shrink, producing thinner and shorter hair strands until hair growth slows down significantly.
        </p>

        <p class="cs-text">
          This type of hair loss usually develops gradually and may run in families.
        </p>

        <p class="cs-text"><strong>Common signs of genetic hair loss include:</strong></p>

        <ul class="feature-list">
          <li>Gradual thinning of hair over time</li>
          <li>Receding hairline in men</li>
          <li>Thinning near the crown area</li>
          <li>Wider hair partition in women</li>
          <li>Reduced hair density compared to earlier years</li>
        </ul>

        <p class="cs-text"><strong>How it is often identified:</strong></p>

        <ul class="feature-list">
          <li>Family history of hair loss</li>
          <li>Progressive thinning pattern on the scalp</li>
          <li>Hair strands becoming finer and weaker over time</li>
        </ul>

        <p class="cs-text">
          Genetic hair loss typically progresses slowly, which is why early identification is important 
          to help manage further hair thinning.
        </p>

      </div>

    </div>

  </div>
</section>
