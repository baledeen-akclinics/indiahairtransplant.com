    <h2 class="results-title">What is Male Pattern Baldness?</h2>

    <div class="results-divider" aria-hidden="true">
      <span class="line"></span>
      <span class="cross">✚</span>
      <span class="line"></span>
    </div>

    <div class="cs-wrap">

      <div class="cs-img">
        <img src="<?= base_url('assets/images/male-pattern-baldness.png') ?>" alt="Male pattern baldness hairline patterns">
      </div>

      <div class="cs-content">

        <p class="cs-text">
          Male pattern baldness is the most common cause of progressive hair loss in men. Medically known as <strong>androgenetic alopecia</strong>, it occurs when genetically sensitive hair follicles react to <strong>dihydrotestosterone (DHT)</strong>, a hormone derived from testosterone.
        </p>

        <p class="cs-text">
          Over time, this sensitivity causes hair follicles to shrink, producing hair that becomes <strong>thinner, shorter, and weaker with each growth cycle</strong>. The condition usually follows a predictable pattern, beginning with recession at the temples, frontal hairline, or crown, while the sides and back of the scalp remain relatively stable.
        </p>

        <p class="cs-text">
          Although male pattern baldness is genetically influenced, the <strong>age of onset and progression rate can vary</strong> from person to person. Early evaluation helps identify the stage of hair loss and allows appropriate treatment planning.
        </p>

        <h3 class="sub-title">Common Hairline Patterns Seen in Male Pattern Baldness</h3>

        <ul class="feature-list">
          <li>
            <strong>M-shaped hairline:</strong> Hair recession begins at both temples while the central hairline remains intact. This pattern is commonly seen in the early stages of male pattern baldness.
          </li>

          <li>
            <strong>U-shaped hairline:</strong> Hair loss progresses further across the frontal scalp, creating a wider and more rounded recession that usually indicates more advanced frontal thinning.
          </li>

          <li>
            <strong>V-shaped hairline:</strong> A pointed central hairline that may be natural in some individuals. However, when combined with temple recession, it may indicate early androgenetic alopecia.
          </li>
        </ul>

      </div>

    </div>

  </div>
</section>
