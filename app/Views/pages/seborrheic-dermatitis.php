        <p class="cs-text">
        Seborrheic dermatitis is a <strong>long-term inflammatory skin condition</strong> that affects areas of the skin where oil-producing glands are active. It commonly develops on the scalp and certain facial regions, where it appears as persistent flaking, redness, and mild itching.
        </p>

        <p class="cs-text">
        Unlike simple dandruff, seborrheic dermatitis involves <strong>visible skin inflammation along with scaling</strong>. The flakes may appear white, yellowish, or greasy, and the affected skin may look slightly irritated or sensitive.
        </p>

        <p class="cs-text">
        The condition develops due to an interaction between natural skin oils and a yeast that normally lives on the skin surface. In some individuals, this interaction triggers inflammation and accelerates skin cell turnover.
        </p>

        <p class="cs-text">
        Seborrheic dermatitis often follows a <strong>recurrent pattern</strong>, meaning symptoms may improve with treatment but can return periodically.
        </p>

        <p class="cs-text">
        Although it is not contagious, the condition may flare up due to stress, weather changes, or hormonal fluctuations.
        </p>

